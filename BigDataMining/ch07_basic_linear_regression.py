import matplotlib.pyplot as plt
import numpy as np
from sklearn.datasets import load_diabetes

# Load the dataset
data = load_diabetes()

# Select only the BMI feature
X = data.data[:, [2]]
Y = data.target

# Plot the data
plt.scatter(X, Y, color="red")
plt.xlabel("BMI")
plt.ylabel("Disease progression")
plt.show()

from sklearn.linear_model import LinearRegression

# Preprocessing: reshape into a matrix
reX = X.reshape(-1, 1)

# Create the model
model = LinearRegression()

# Train the model => find a 'w'
model.fit(reX, Y)

# Check the results
print("Weight:", model.coef_)
print("Constant:", model.intercept_)

y_pred = model.predict(reX)  # Generate predictions

plt.scatter(X, Y, color="red")  # Original data (points)
plt.plot(X, y_pred)  # Predicted values for X (line)
plt.show()

